"""
BattLab — Report Generation Service (PDF + CSV + JSON)
"""
from __future__ import annotations

import csv
import io
import json
import os
from datetime import datetime
from pathlib import Path
from typing import Optional

# ReportLab for PDF
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.platypus import (
    Paragraph, Spacer, Table, TableStyle, SimpleDocTemplate, HRFlowable,
)


REPORT_DIR = Path(os.environ.get("BATTLAB_REPORT_DIR", "./reports"))
REPORT_DIR.mkdir(parents=True, exist_ok=True)


def generate_pdf_report(
    project: dict,
    requirement: Optional[dict],
    configuration: dict,
    simulation_run: dict,
    timeseries: list[dict],
    constraints: list[dict],
    assumptions: list[str],
    report_id: int,
) -> str:
    """Generate an engineering PDF report. Returns the file path."""
    filename = f"battlab_report_{report_id}_{datetime.utcnow().strftime('%Y%m%d_%H%M%S')}.pdf"
    filepath = REPORT_DIR / filename

    doc = SimpleDocTemplate(
        str(filepath),
        pagesize=A4,
        rightMargin=2 * cm,
        leftMargin=2 * cm,
        topMargin=2.5 * cm,
        bottomMargin=2 * cm,
    )

    styles = getSampleStyleSheet()
    story = []

    # ── Header ────────────────────────────────────────────────────────────────
    title_style = ParagraphStyle("Title", parent=styles["Heading1"], fontSize=18, spaceAfter=4)
    story.append(Paragraph("BattLab Engineering Report", title_style))
    story.append(Paragraph(
        f"<b>DISCLAIMER:</b> This report is generated by a prototype engineering screening tool. "
        "Simulated results are not experimental measurements. This report does not constitute a "
        "battery safety certification or manufacturing approval.",
        ParagraphStyle("Disclaimer", parent=styles["Normal"], fontSize=8, textColor=colors.red)
    ))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.grey))
    story.append(Spacer(1, 0.3 * cm))

    # ── Project Info ──────────────────────────────────────────────────────────
    story.append(Paragraph("1. Project Information", styles["Heading2"]))
    proj_data = [
        ["Field", "Value"],
        ["Project Name", project.get("name", "N/A")],
        ["Application", project.get("application_category", "N/A")],
        ["Engineer", project.get("engineer_label", "N/A") or "—"],
        ["Design Version", project.get("design_version", "N/A")],
        ["Report Generated", datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")],
        ["Model Version", simulation_run.get("model_version", "N/A")],
        ["Simulation Run ID", str(simulation_run.get("id", "N/A"))],
    ]
    story.append(_make_table(proj_data))
    story.append(Spacer(1, 0.4 * cm))

    # ── Requirements ──────────────────────────────────────────────────────────
    story.append(Paragraph("2. Requirements", styles["Heading2"]))
    if requirement:
        req_data = [
            ["Requirement", "Value", "Type"],
            ["Target Voltage", f"{requirement.get('target_voltage_v', '—')} V", _hc(requirement, "target_voltage_v")],
            ["Target Energy", f"{requirement.get('target_energy_wh', '—')} Wh", _hc(requirement, "target_energy_wh")],
            ["Energy Type", "Usable" if requirement.get("energy_is_usable") else "Nominal", "—"],
            ["Max Mass", f"{requirement.get('max_mass_kg', '—')} kg", _hc(requirement, "max_mass_kg")],
            ["Max Cost", f"${requirement.get('max_cost_usd', '—')}", _hc(requirement, "max_cost_usd")],
            ["Min Ambient Temp", f"{requirement.get('min_ambient_temp_c', '—')} °C", "—"],
            ["Max Ambient Temp", f"{requirement.get('max_ambient_temp_c', '—')} °C", "—"],
            ["Cooling", requirement.get("cooling_preference", "—"), "—"],
        ]
        story.append(_make_table(req_data))
    else:
        story.append(Paragraph("No requirements recorded.", styles["Normal"]))
    story.append(Spacer(1, 0.4 * cm))

    # ── Configuration ─────────────────────────────────────────────────────────
    story.append(Paragraph("3. Configuration", styles["Heading2"]))
    cfg = configuration
    cfg_data = [
        ["Parameter", "Value"],
        ["Label", cfg.get("label", "—")],
        ["Series Count (Ns)", str(cfg.get("ns", "—"))],
        ["Parallel Count (Np)", str(cfg.get("np", "—"))],
        ["Total Cells", str(cfg.get("calc_total_cells", "—"))],
        ["Nominal Voltage (calc)", f"{cfg.get('calc_nominal_voltage_v', '—')} V"],
        ["Nominal Energy (calc)", f"{cfg.get('calc_nominal_energy_wh', '—')} Wh"],
        ["Cooling Type", cfg.get("cooling_type", "—")],
        ["Usable SOC Window", f"{cfg.get('usable_soc_window', 0)*100:.0f}%"],
    ]
    story.append(_make_table(cfg_data))
    story.append(Spacer(1, 0.4 * cm))

    # ── Simulation Results ────────────────────────────────────────────────────
    story.append(Paragraph("4. Simulation Results (Modelled)", styles["Heading2"]))
    story.append(Paragraph(
        "The following values are outputs of the BattLab lumped electrical and thermal simulation. "
        "They are not experimental measurements. See Section 6 for assumptions and limitations.",
        ParagraphStyle("Note", parent=styles["Normal"], fontSize=9, textColor=colors.darkgrey)
    ))
    res_data = [
        ["Metric", "Value", "Status"],
        ["Nominal Voltage", f"{simulation_run.get('result_nominal_voltage_v', '—')} V", "Calculated"],
        ["Nominal Energy", f"{simulation_run.get('result_nominal_energy_wh', '—')} Wh", "Calculated"],
        ["Usable Energy (est.)", f"{simulation_run.get('result_usable_energy_wh', '—')} Wh", "Estimated"],
        ["Max Modelled Temp", f"{simulation_run.get('result_max_temp_c', '—')} °C", "Simulated"],
        ["Min SOC", f"{(simulation_run.get('result_min_soc') or 0)*100:.1f}%", "Simulated"],
        ["Energy Delivered", f"{simulation_run.get('result_energy_delivered_wh', '—')} Wh", "Simulated"],
        ["SOH (Capacity)", f"{simulation_run.get('result_soh_capacity_pct', 100.0):.1f}%", "SEI Degradation Model"],
        ["SOH (Resistance)", f"{simulation_run.get('result_soh_resistance_pct', 100.0):.1f}%", "SEI Degradation Model"],
        ["Charge Throughput", f"{simulation_run.get('result_throughput_ah', 0.0):.2f} Ah", "Simulated Mission"],
        ["Equivalent Full Cycles", f"{simulation_run.get('result_efc', 0.0):.3f} EFC", "Calculated"],
    ]
    story.append(_make_table(res_data))
    story.append(Spacer(1, 0.4 * cm))

    # ── Constraint Checks ─────────────────────────────────────────────────────
    story.append(Paragraph("5. Constraint Checks", styles["Heading2"]))
    if constraints:
        c_data = [["Rule", "Status", "Observed", "Threshold", "Units", "Explanation"]]
        for c in constraints:
            c_data.append([
                c.get("rule_id", "—"),
                c.get("status", "—").upper(),
                str(c.get("observed_value", "—")),
                str(c.get("threshold", "—")),
                c.get("units", "—"),
                c.get("explanation", "—")[:80],
            ])
        story.append(_make_table(c_data, small=True))
    story.append(Spacer(1, 0.4 * cm))

    # ── Assumptions ───────────────────────────────────────────────────────────
    story.append(Paragraph("6. Assumptions and Limitations", styles["Heading2"]))
    story.append(Paragraph(
        "The following provisional assumptions were used in this simulation:",
        styles["Normal"]
    ))
    for a in assumptions:
        story.append(Paragraph(f"• {a}", styles["Normal"]))
    story.append(Spacer(1, 0.3 * cm))
    story.append(Paragraph(
        "IMPORTANT LIMITATIONS: This is a prototype screening tool using lumped electrical "
        "and thermal models. Results do not replace validated electrochemical simulation, "
        "physical prototype testing, or regulatory approval. The thermal model does not "
        "resolve internal temperature gradients. Cell ageing is represented by sensitivity "
        "multipliers only, not a validated physical ageing law.",
        ParagraphStyle("Warn", parent=styles["Normal"], fontSize=8, textColor=colors.red)
    ))

    doc.build(story)
    return str(filepath)


def _hc(req: dict, key: str) -> str:
    hcs = req.get("hard_constraints") or []
    return "Hard Constraint" if key in hcs else "Objective"


def _make_table(data: list, small: bool = False) -> Table:
    styles_list = [
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1e3a5f")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTSIZE", (0, 0), (-1, -1), 8 if small else 9),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f5f7fa")]),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]
    t = Table(data, repeatRows=1)
    t.setStyle(TableStyle(styles_list))
    return t


def generate_csv_timeseries(timeseries: list[dict], report_id: int) -> str:
    """Generate CSV for time-series data. Returns file path."""
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    filename = f"battlab_timeseries_{report_id}_{datetime.utcnow().strftime('%Y%m%d_%H%M%S')}.csv"
    filepath = REPORT_DIR / filename
    if not timeseries:
        with open(filepath, "w", newline="") as f:
            writer = csv.writer(f)
            writer.writerow(["t_s", "current_a", "soc", "temp_c", "voltage_v", "power_loss_w"])
            writer.writerow(["# No time-series data recorded for this simulation run"])
        return str(filepath)
    fieldnames = list(timeseries[0].keys())
    with open(filepath, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(timeseries)
    return str(filepath)


def generate_json_config(configuration: dict, cell_spec: dict, report_id: int) -> str:
    """Export configuration as JSON. Returns file path."""
    filename = f"battlab_config_{report_id}_{datetime.utcnow().strftime('%Y%m%d_%H%M%S')}.json"
    filepath = REPORT_DIR / filename
    payload = {
        "export_version": "battlab-0.1.0",
        "exported_at": datetime.utcnow().isoformat(),
        "disclaimer": (
            "This export is from a prototype engineering screening tool. "
            "Values may be provisional or unverified."
        ),
        "configuration": configuration,
        "cell_spec": cell_spec,
    }
    with open(filepath, "w") as f:
        json.dump(payload, f, indent=2, default=str)
    return str(filepath)
